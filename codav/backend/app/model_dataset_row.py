#Used to store preview rows for datasets where each record is saved as JSON
#Allows CODAV to display previews without loading full CSV files every time
from sqlalchemy import Integer, ForeignKey, TIMESTAMP, func
from sqlalchemy.dialects.mysql import JSON
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.base import Base #Used by all pf the SQLAlchemy models


#Represents a single preview row linked to a parent dataset
#Each row belongs to exactly one dataset via dataset_id
#row_index preserves original CSV ordering so previews stay deterministic
class DatasetRow(Base):
    __tablename__ = "dataset_rows"

    #Primary key for dataset_rows table
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)

    #Foreign key linking row to datasets.id
    #ondelete CASCADE ensures rows are removed automatically if dataset is deleted
    dataset_id: Mapped[int] = mapped_column(
        Integer,
        ForeignKey("datasets.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    #Original row position inside the dataset
    #Used to keep preview ordering stable
    row_index: Mapped[int] = mapped_column(Integer, nullable=False)

    #Raw dataset row stored as JSON
    #Supports heterogeneous datasets without dynamic schema changes
    data: Mapped[dict] = mapped_column(JSON, nullable=False)

    #Timestamp automatically generated by database
    #server_default keeps behaviour consistent even outside FastAPI
    created_at: Mapped[str] = mapped_column(
        TIMESTAMP, server_default=func.now(), nullable=False
    )

    #Relationship so Dataset.rows can be accessed via ORM
    dataset = relationship("Dataset", back_populates="rows")